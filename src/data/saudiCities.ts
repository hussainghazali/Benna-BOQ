export const top20Cities: SaudiCity[] = allSaudiCities
  .filter((c) => c.population)
  .sort((a, b) => {
    const popA = parseInt((a.population || "0").replace(/,/g, ""));
    const popB = parseInt((b.population || "0").replace(/,/g, ""));
    return popB - popA;
  })
  .slice(0, 20);

